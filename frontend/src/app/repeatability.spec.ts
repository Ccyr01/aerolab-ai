import { TestBed } from '@angular/core/testing';
import { provideHttpClient } from '@angular/common/http';
import { RepeatabilityChart } from './repeatability';

describe('Repeatability chart', () => {
  it('preserves acquisition order and renders sample SD, frequency, and run counts when switching patterns', async () => {
    TestBed.configureTestingModule({ providers: [provideHttpClient()] });
    spyOn(RepeatabilityChart.prototype, 'ngAfterViewInit');
    const fixture = TestBed.createComponent(RepeatabilityChart);
    fixture.detectChanges();
    const chart = fixture.componentInstance;
    const plotly = await import('plotly.js-basic-dist-min');
    const internals = chart as any;
    internals.plotly = plotly.default;
    const point = (Step: number, CurrentAction: number) => ({ Step, CurrentAction, Mean_Delta_Cl: 0.05, SD_Delta_Cl: 0.01, RunCount: 10 });
    internals.groups = { random_1: [point(2, 1), point(0, 0), point(1, 20)], ascending: [point(0, 0), point(1, 1)], descending: [point(2, 1), point(0, 0), point(1, 20)] };
    const original = JSON.stringify(internals.groups);
    chart.loading.set(false);
    fixture.detectChanges();
    const select: HTMLSelectElement = fixture.nativeElement.querySelector('select');
    expect(select.options.length).toBe(8);
    select.value = 'random_1';
    select.dispatchEvent(new Event('change'));
    fixture.detectChanges();
    await fixture.whenStable();
    const traces = internals.plot.nativeElement.data;
    expect(traces[2].x).toEqual([0, 1, 2]);
    expect(traces[2].customdata).toEqual([[0, 0.01, 10, 0, 'Randomized pattern 1'], [20, 0.01, 10, 1, 'Randomized pattern 1'], [1, 0.01, 10, 2, 'Randomized pattern 1']]);
    expect(traces[0].y[0]).toBeCloseTo(0.04);
    expect(traces[1].y[0]).toBeCloseTo(0.06);
    expect(traces[1].fill).toBe('tonexty');
    expect(traces[2].hovertemplate).toContain('Hz');
    expect(chart.runCount()).toBe(10);
    select.value = 'ascending';
    select.dispatchEvent(new Event('change'));
    await fixture.whenStable();
    expect(internals.plot.nativeElement.data[2].x).toEqual([0, 1]);
    select.value = 'comparison';
    select.dispatchEvent(new Event('change'));
    await fixture.whenStable();
    const comparison = internals.plot.nativeElement.data;
    expect(comparison.length).toBe(6);
    expect(comparison[5].x).toEqual([0, 1, 2]);
    expect(comparison[5].customdata.map((row: unknown[]) => row[0])).toEqual([0, 20, 1]);
    expect(comparison[2].line.color).not.toBe(comparison[5].line.color);
    expect(comparison[2].line.dash).not.toBe(comparison[5].line.dash);
    expect(comparison[4].fill).toBe('tonexty');
    expect(comparison[4].legendgroup).toBe(comparison[5].legendgroup);
    expect(comparison[5].hovertemplate).toContain('Between-run sample SD');
    const axis: HTMLSelectElement = fixture.nativeElement.querySelector('#repeatability-axis');
    axis.value = 'frequency';
    axis.dispatchEvent(new Event('change'));
    await fixture.whenStable();
    const frequency = internals.plot.nativeElement.data;
    expect(frequency[2].x).toEqual([0, 1]);
    expect(frequency[5].x).toEqual([0, 1, 20]);
    expect(frequency[5].customdata.map((row: unknown[]) => row[3])).toEqual([0, 2, 1]);
    expect(internals.plot.nativeElement.layout.xaxis.title.text).toBe('Forcing Frequency (Hz)');
    select.value = 'random_1';
    select.dispatchEvent(new Event('change'));
    await fixture.whenStable();
    expect(internals.plot.nativeElement.data[2].x).toEqual([0, 1, 20]);
    axis.value = 'step';
    axis.dispatchEvent(new Event('change'));
    await fixture.whenStable();
    expect(internals.plot.nativeElement.data[2].x).toEqual([0, 1, 2]);
    expect(JSON.stringify(internals.groups)).toBe(original);
    fixture.destroy();
    expect(internals.plot.nativeElement.data).toBeUndefined();
  });
});
